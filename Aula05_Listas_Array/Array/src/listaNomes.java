public class listaNomes {
    public static void main(String[] args) {
        String[] nomes = new String[5];

        nomes[0] = "Maria";
        nomes[1] = "João";
        nomes[2] = "José";
        nomes[3] = "Mateus";
        nomes[4] = "Paulo";

        for (String nome : nomes) {
            System.out.println(nome);
        }



    }
}
